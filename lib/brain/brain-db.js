/**
 * Read the brain-schema.sql from known source locations.
 * Returns null if not found (schema install skipped — daemon still starts).
 * @returns {string | null}
 */
function readSchema() {
  for (const p of SCHEMA_SOURCE_PATHS) {
    try {
      return fs.readFileSync(p, 'utf-8');
    } catch {
      // try next
    }
  }
  return null;
}

/**
 * Write a file to the target project, creating parent dirs as needed.
 * Skips if the file already exists and force is false.
 * @param {string} dest  Absolute path to destination file.
 * @param {string} content  File content.
 * @param {{ force: boolean, dryRun: boolean, verbose: boolean }} opts
 * @returns {'written' | 'skipped' | 'dry-run'}
 */
function writeFile(dest, content, { force, dryRun, verbose }) {
  const exists = fs.existsSync(dest);
  if (exists && !force) {
    if (verbose) console.log(`  skip (exists) ${path.relative(process.cwd(), dest)}`);
    return 'skipped';
  }
  if (dryRun) {
    if (verbose) console.log(`  [dry-run] ${exists ? 'overwrite' : 'write'} ${path.relative(process.cwd(), dest)}`);
    return 'dry-run';
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, content, 'utf-8');
  if (verbose) console.log(`  write ${path.relative(process.cwd(), dest)}`);
  return 'written';
}

/**
 * Append or update key=value pairs in target .env.
 *
 * Default behaviour (force=false): skip keys that are already set.
 * Force behaviour (force=true): replace existing values in-place so that
 * re-running `brain restore --force` refreshes credentials like BRAIN_DB_TOKEN.
 *
 * @param {string} envPath  Absolute path to .env.
 * @param {Record<string, string>} vars
 * @param {{ dryRun: boolean, verbose: boolean, force?: boolean }} opts
 */
function appendEnvVars(envPath, vars, { dryRun, verbose, force = false }) {
  let existing = '';
  try { existing = fs.readFileSync(envPath, 'utf-8'); } catch { /* new file */ }

  // Build existing key set once before the loop to avoid re-splitting on every
  // iteration and to ensure the check is against the original file, not mutations.
  // No .trim() on key extraction — must match the startsWith(`${key}=`) check
  // below; trimming would find indented keys in the set but fail to match them
  // in the replacement. Standard .env files do not indent keys. Note: keys with
  // trailing spaces before '=' (e.g. 'FOO =bar') are out-of-scope and treated
  // as absent — this is acceptable for provisioner-written .env files.
  const existingKeys = new Set(
    existing.split('\n')
      .filter((l) => l.includes('=') && !l.trim().startsWith('#'))
      .map((l) => l.slice(0, l.indexOf('='))),
  );

  const toAppend = [];   // new keys not yet in .env
  let updated = existing; // will hold in-place replacements when force=true

  for (const [key, value] of Object.entries(vars)) {
    if (existingKeys.has(key)) {
      if (force) {
        // Replace existing value in-place — required for credential refresh.
        // Use string-based line replacement (not RegExp) to avoid metacharacter issues.
        if (verbose) console.log(`  [force] update ${key} in .env`);
        if (!dryRun) {
          updated = updated.split('\n').map((l) => l.startsWith(`${key}=`) ? `${key}=${value}` : l).join('\n');
        } else if (verbose) {
          console.log(`  [dry-run] would update ${key} in .env`);
        }
      } else {
        if (verbose) console.log(`  skip (already set) ${key} in .env`);
      }
      continue;
    }
    toAppend.push(`${key}=${value}`);
  }

  if (dryRun) {
    if (verbose) {
      for (const l of toAppend) console.log(`  [dry-run] append .env: ${l.split('=')[0]}=<value>`);
    }
    return;
  }

  // Write back updated content (in-place replacements).
  if (updated !== existing) {
    fs.writeFileSync(envPath, updated, 'utf-8');
  }

  // Append new keys.
  if (toAppend.length > 0) {
    const suffix = (updated.endsWith('\n') || updated === '' ? '' : '\n') + toAppend.join('\n') + '\n';
    fs.appendFileSync(envPath, suffix, 'utf-8');
    if (verbose) {
      for (const l of toAppend) console.log(`  append .env: ${l.split('=')[0]}=<redacted>`);
    }
  }
}

/**
 * Detect the package manager used in a target directory.
 * Returns 'bun' | 'yarn' | 'pnpm' | 'npm' | null (no package.json found).
 * @param {string} targetDir
 * @returns {'bun' | 'yarn' | 'pnpm' | 'npm' | null}
 */
export function detectPackageManager(targetDir) {
  if (!fs.existsSync(path.join(targetDir, 'package.json'))) return null; // nosemgrep
  // Bun 1.1+ uses the text lockfile `bun.lock`; older Bun installations use
  // `bun.lockb`. Either is authoritative evidence that `bun add` is the
  // supported installer for the restored project.
  if (fs.existsSync(path.join(targetDir, 'bun.lockb')) || fs.existsSync(path.join(targetDir, 'bun.lock'))) return 'bun'; // nosemgrep
  if (fs.existsSync(path.join(targetDir, 'yarn.lock')))        return 'yarn'; // nosemgrep
  if (fs.existsSync(path.join(targetDir, 'pnpm-lock.yaml')))   return 'pnpm'; // nosemgrep
  return 'npm';
}

/**
 * Install @libsql/client in a target project using its detected package manager.
 * No-op if already present in dependencies or no package.json found.
 * @param {string} targetDir
 * @param {{ dryRun: boolean, verbose: boolean }} opts
 */
export function installLibsqlClient(targetDir, { dryRun, verbose }) {
  const pm = detectPackageManager(targetDir);
  if (!pm) {
    if (verbose) console.log('  [brain-db] No package.json found — skipping @libsql/client install.');
    return;
  }

  // Check if already installed.
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(targetDir, 'package.json'), 'utf-8')); // nosemgrep
    const deps = { ...pkg.dependencies, ...pkg.devDependencies };
    if (deps['@libsql/client']) {
      if (verbose) console.log('  [brain-db] @libsql/client already in package.json — skipping install.');
      return;
    }
  } catch {
    // Malformed package.json — skip install, don't break provisioning.
    if (verbose) console.log('  [brain-db] Could not parse package.json — skipping @libsql/client install.');
    return;
  }

  // Use execFileSync with explicit args array (not a shell string) to prevent
  // command injection if targetDir contains shell metacharacters.
  const pmConfigs = {
    bun:  { bin: 'bun',  args: ['add', '@libsql/client', '--cwd', targetDir] },
    yarn: { bin: 'yarn', args: ['add', '@libsql/client', '--cwd', targetDir] },
    pnpm: { bin: 'pnpm', args: ['add', '@libsql/client', '--dir', targetDir] },
    npm:  { bin: 'npm',  args: ['install', '@libsql/client', '--prefix', targetDir] },
  };
  const { bin, args } = pmConfigs[pm];

  if (dryRun) {
    if (verbose) console.log(`  [dry-run] install @libsql/client via ${pm}: ${bin} ${args.join(' ')}`);
    return;
  }

  if (verbose) console.log(`  [brain-db] Installing @libsql/client via ${pm}…`);
  try {
    execFileSync(bin, args, { stdio: verbose ? 'inherit' : 'pipe' });
    if (verbose) console.log('  [brain-db] @libsql/client installed.');
  } catch (err) {
    // Non-fatal — db.ts is still written; user can install manually.
    console.warn(`  [brain-db] @libsql/client install failed (${pm}): ${err.message}. Install manually: ${bin} ${args.join(' ')}`);
  }
}

/**
 * Append a gitignore entry to target .gitignore if not already present.
 * @param {string} gitignorePath  Absolute path to .gitignore.
 * @param {string} entry          Line to add (e.g. '.brain/brain.db').
 * @param {{ dryRun: boolean, verbose: boolean }} opts
 */
function appendGitignoreEntry(gitignorePath, entry, { dryRun, verbose }) {
  let existing = '';
  try { existing = fs.readFileSync(gitignorePath, 'utf-8'); } catch { /* new file */ }

  // Match exact line (with or without trailing whitespace).
  const alreadyPresent = existing.split('\n').some((l) => l.trim() === entry);
  if (alreadyPresent) {
    if (verbose) console.log(`  skip (already present) .gitignore: ${entry}`);
    return;
  }

  if (dryRun) {
    if (verbose) console.log(`  [dry-run] append .gitignore: ${entry}`);
    return;
  }

  const toAppend = (existing.endsWith('\n') || existing === '' ? '' : '\n') + entry + '\n';
  fs.appendFileSync(gitignorePath, toAppend, 'utf-8');
  if (verbose) console.log(`  append .gitignore: ${entry}`);
}

