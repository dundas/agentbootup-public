/** PRD-0014 FR-07 — committed path in each brain repo (developer-facing contract). */
export const BRAIN_SCHEMA_REL_COMMITTED = path.join('brain', 'brain-schema.sql');
/** Same bytes as {@link BRAIN_SCHEMA_REL_COMMITTED}; under .brain/ for applySchema / ignored runtime. */
export const BRAIN_SCHEMA_REL_RUNTIME = path.join('.brain', 'brain-schema.sql');

/**
 * Path to use for BRAIN_DB_SCHEMA_PATH: prefer committed `brain/brain-schema.sql`, else legacy `.brain/` copy.
 * @param {string} projectRoot Absolute project root
 * @returns {string | null} null if neither file exists
 */
export function resolveBrainSchemaPathForProject(projectRoot) {
  const committed = path.join(projectRoot, BRAIN_SCHEMA_REL_COMMITTED);
  const runtime = path.join(projectRoot, BRAIN_SCHEMA_REL_RUNTIME);
  if (fs.existsSync(committed)) return committed;
  if (fs.existsSync(runtime)) return runtime;
  return null;
}

