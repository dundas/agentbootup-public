/**
 * Provision brain.db for a target project.
 *
 * Calls the agentbootup server's /v1/brain-db/provision endpoint to get the
 * per-brain DB URL and auth token. If the server doesn't support this endpoint yet,
 * falls back to file-only mode (db.ts + schema written, no remote sync configured).
 *
 * Sync is handled by the `agentbootup-brain-db-<id>` daemon (agent-process),
 * started by `agentbootup daemon start`. No session hooks are written.
 *
 * @param {{
 *   brainId: string,
 *   target: string,
 *   apiKey: string,
 *   serverUrl: string,
 *   force: boolean,
 *   dryRun: boolean,
 *   verbose: boolean,
 * }} opts
 * @returns {Promise<{
 *   mode: 'embedded-replica' | 'file-only',
 *   message: string,
 * }>}
 */
export async function provisionBrainDb(opts) {
  const { brainId, target, apiKey, serverUrl, force, dryRun, verbose } = opts;

  let dbUrl = null;
  let dbToken = null;

  // ── Step 1: Request DB URL + JWT from agentbootup server ──────────────────
  // Skip the server call in dry-run — provision creates a JWT credential and
  // has a side effect (server may record the provision). Dry-run must be
  // read-only; show a preview message instead.
  if (dryRun) {
    if (verbose) console.log('  [dry-run] would call POST /v1/brain-db/provision — skipping server call');
    return { mode: 'file-only', message: 'brain.db provisioning skipped (dry-run)' };
  }

  try {
    const resp = await fetch(apiUrl(serverUrl, '/v1/brain-db/provision'), {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${apiKey}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ brain_id: brainId }),
      signal: AbortSignal.timeout(PROVISION_TIMEOUT_MS),
    });

    if (resp.ok) {
      const body = await resp.json();
      dbUrl = body?.data?.db_url ?? null;
      dbToken = body?.data?.db_token ?? null;
    } else if (resp.status === 404) {
      if (verbose) console.log('  [brain-db] Server does not support brain-db provisioning yet — file-only mode.');
    } else {
      const msg = await resp.text().catch(() => `HTTP ${resp.status}`);
      if (verbose) console.log(`  [brain-db] Provision request failed (${resp.status}): ${msg} — file-only mode.`);
    }
  } catch (err) {
    if (verbose) console.log(`  [brain-db] Provision request error: ${err.message} — file-only mode.`);
  }

  const mode = dbUrl ? 'embedded-replica' : 'file-only';

  // ── Step 2: Install @libsql/client in target project ─────────────────────
  installLibsqlClient(target, { dryRun, verbose });

  // ── Step 3: Write .brain/db.ts ────────────────────────────────────────────
  writeFile(path.join(target, '.brain/db.ts'), DB_TS_TEMPLATE, { force, dryRun, verbose }); // nosemgrep

  // ── Step 4: Copy brain-schema.sql (FR-07 committed + runtime mirror) ─────
  const schema = readSchema();
  if (schema) {
    writeFile(path.join(target, BRAIN_SCHEMA_REL_COMMITTED), schema, { force, dryRun, verbose }); // nosemgrep
    writeFile(path.join(target, BRAIN_SCHEMA_REL_RUNTIME), schema, { force, dryRun, verbose }); // nosemgrep
  } else {
    if (verbose) console.log('  [brain-db] brain-schema.sql not found — skipping. Run `agentbootup brain restore --force` after templates/brain/brain-schema.sql is bundled.');
  }

  // ── Step 5: Append BRAIN_DB_URL + BRAIN_DB_TOKEN to .env ─────────────────
  if (dbUrl && dbToken) {
    appendEnvVars(
      path.join(target, '.env'), // nosemgrep
      { BRAIN_DB_URL: dbUrl, BRAIN_DB_TOKEN: dbToken },
      { dryRun, verbose, force },
    );
  }

  // ── Step 6: Allocate inbox port + generate webhook secret (AB-1, AB-2) ──────
  let inboxPort = null;
  let inboxSecret = null;
  if (!dryRun) {
    try {
      inboxPort = await allocateInboxPort(brainId);
      // Don't attempt mech-plane registration at provision time — the mech-plane
      // URL is distinct from the agentbootup server URL and is not available here.
      // Registration happens in getInboxAgentEntries() during `daemon start`.
      const webhookResult = await provisionWebhookSecret(brainId, inboxPort, {
        mechPlaneUrl: null,
        verbose,
      });
      inboxSecret = webhookResult.secret;
    } catch (err) {
      // Non-fatal — inbox daemon can be provisioned later.
      if (verbose) console.log(`  [brain-db] inbox provisioning error (non-fatal): ${err.message}`);
    }
    // Set the opt-in flag separately — a flag write failure must not be
    // confused with a provisioning failure (port + secret may already be set).
    if (inboxPort !== null && inboxSecret !== null) {
      try {
        await setInboxEnabled(brainId, true);
      } catch (err) {
        if (verbose) console.log(`  [brain-db] inbox flag write error (non-fatal): ${err.message}`);
      }
    }
  } else if (verbose) {
    console.log('  [dry-run] would allocate inbox port (8767–8867) and generate HMAC webhook secret');
  }

  // ── Step 7: Append inbox env vars to .env (AB-4) ─────────────────────────
  if (inboxPort !== null && inboxSecret !== null) {
    appendEnvVars(
      path.join(target, '.env'), // nosemgrep
      {
        AGENTBOOTUP_INBOX_PORT: String(inboxPort),
        AGENTBOOTUP_INBOX_WEBHOOK_SECRET: inboxSecret,
      },
      { dryRun, verbose, force },
    );
  }

  // ── Step 8: Add .brain/brain.db to .gitignore ─────────────────────────────
  appendGitignoreEntry(
    path.join(target, '.gitignore'), // nosemgrep
    '.brain/brain.db',
    { dryRun, verbose },
  );

  const modeLabel = mode === 'embedded-replica'
    ? 'embedded-replica (run `agentbootup daemon start` to activate sync)'
    : 'file-only (no remote sync — run restore again after server is configured)';
  return { mode, message: `brain.db provisioned — ${modeLabel}` };
}

/**
 * Provision brain.db in LOCAL-FIRST boot mode — no server call.
 *
 * Called by `agentbootup brain restore --boot`. Writes the same local files as
 * {@link provisionBrainDb} (db.ts, brain-schema.sql, .gitignore) but skips the
 * `/v1/brain-db/provision` network call and inbox port allocation. The generated
 * db.ts reads BRAIN_DB_URL / BRAIN_DB_TOKEN from the process environment at
 * runtime; sync is automatically configured when those env vars are present.
 * Sync is never required for the boot to succeed.
 *
 * @param {{
 *   brainId: string,
 *   target: string,
 *   verbose?: boolean,
 * }} opts
 * @returns {{ mode: 'file-only', message: string }}
 */
export async function provisionBrainDbBoot({ brainId: _brainId, target, verbose = false }) {
  // Boot containers are pre-baked — @libsql/client must already be installed before
  // boot runs. We skip the install step (installLibsqlClient) because execFileSync
  // hangs indefinitely when the package registry is unreachable inside a locked
  // container, defeating fail-closed boot. The generated .brain/db.ts hard-imports
  // @libsql/client, so the package MUST be present in target/node_modules; if it
  // is not, we fail with a clear error rather than emitting a broken runtime.
  const libsqlClientDir = path.join(target, 'node_modules', '@libsql', 'client');
  if (!fs.existsSync(libsqlClientDir)) {
    throw new Error(
      '[brain-db] boot mode requires @libsql/client to be pre-installed in the target ' +
      `(${target}/node_modules/@libsql/client not found). Install it before running boot.`,
    );
  }

  if (verbose) {
    console.log('  [brain-db] boot mode: @libsql/client verified (pre-baked container)');
  }

  // Write .brain/db.ts — the template reads BRAIN_DB_URL/BRAIN_DB_TOKEN from env
  // at runtime, so sync is automatically configured when those env vars are present.
  writeFile(path.join(target, '.brain/db.ts'), DB_TS_TEMPLATE, { force: false, dryRun: false, verbose }); // nosemgrep

  // Copy brain-schema.sql to both committed and runtime locations.
  const schema = readSchema();
  if (schema) {
    writeFile(path.join(target, BRAIN_SCHEMA_REL_COMMITTED), schema, { force: false, dryRun: false, verbose }); // nosemgrep
    writeFile(path.join(target, BRAIN_SCHEMA_REL_RUNTIME), schema, { force: false, dryRun: false, verbose }); // nosemgrep
  } else if (verbose) {
    console.log('  [brain-db] brain-schema.sql not found — skipping schema install.');
  }

  // Add .brain/brain.db to .gitignore (idempotent).
  appendGitignoreEntry(
    path.join(target, '.gitignore'), // nosemgrep
    '.brain/brain.db',
    { dryRun: false, verbose },
  );

  return {
    mode: 'file-only',
    message: 'brain.db provisioned (local-first boot; sync configured from env vars at runtime)',
  };
}
