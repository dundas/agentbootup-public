/**
 * brain-db.js — Brain DB provisioning helpers.
 *
 * Called by `agentbootup brain restore` as Phase 4 (memory sync).
 * Provisions a libSQL embedded-replica brain.db for the target project.
 *
 * What this does:
 *   - Calls /v1/brain-db/provision on agentbootup server to get DB URL + auth token
 *   - Writes .brain/db.ts (libSQL client init + sync helpers) to target project
 *   - Copies brain-schema.sql to brain/brain-schema.sql (FR-07) and .brain/brain-schema.sql (runtime mirror)
 *   - Appends BRAIN_DB_URL + BRAIN_DB_TOKEN to target project .env
 *   - Allocates inbox port (8767–8867) and generates HMAC webhook secret (AB-1, AB-2)
 *   - Appends AGENTBOOTUP_INBOX_PORT + AGENTBOOTUP_INBOX_WEBHOOK_SECRET to .env (AB-4)
 *   - Adds .brain/brain.db to target project .gitignore (idempotent)
 *
 * Sync is handled by the agentbootup-brain-db-<id> agent-process daemon
 * (registered by `agentbootup daemon start`), not by session hooks.
 * The embedded replica's syncInterval:300 keeps data fresh in the background.
 *
 * If BRAIN_DB_URL is not available (server doesn't support it yet),
 * runs in file-only mode: db.ts and schema still written, no remote sync.
 *
 * The generated .brain/db.ts now degrades to local-only mode if the remote
 * sync target is unreachable at startup and exposes syncDb()/verifySyncHealth()
 * so downstream consumers can adopt the same best-effort replica contract.
 */

