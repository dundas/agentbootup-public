const DB_TS_TEMPLATE = `// .brain/db.ts — libSQL embedded-replica client for brain.db
// Auto-generated by agentbootup brain restore. Do not edit manually.
// Re-run \`agentbootup brain restore\` to regenerate.
import { createClient } from '@libsql/client';

const localUrl = 'file:.brain/brain.db';
const syncUrl = process.env.BRAIN_DB_URL || null;
const authToken = process.env.BRAIN_DB_TOKEN || undefined;

const syncConfigured = Boolean(syncUrl && authToken);

export let brainDbMode = syncConfigured ? 'embedded-replica' : 'file-only';

function createLocalClient() {
  if (!syncConfigured) return createClient({ url: localUrl });
  try {
    return createClient({ url: localUrl, syncUrl, authToken, syncInterval: 300 });
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    console.warn(\`[brain-db] remote sync unavailable at startup; continuing with local replica: \${message}\`);
    brainDbMode = 'embedded-replica-offline';
    return createClient({ url: localUrl });
  }
}

export const db = createLocalClient();

function canAttemptRemoteSync() {
  return syncConfigured && brainDbMode !== 'embedded-replica-offline';
}

export async function syncDb(client = db) {
  if (!canAttemptRemoteSync() || typeof client?.sync !== 'function') return;
  await client.sync();
}

export async function verifySyncHealth(client = db) {
  if (!syncConfigured) return true;
  if (brainDbMode === 'embedded-replica-offline') return false;

  const probeKey = \`agentbootup-sync-probe-\${Date.now()}\`;
  const probeValue = 'ok';
  const remoteClient = createClient({ url: syncUrl, authToken });

  try {
    await client.execute({
      sql: 'INSERT INTO schema_meta (key, value) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value',
      args: [probeKey, probeValue],
    });
    await syncDb(client);

    const result = await remoteClient.execute({
      sql: 'SELECT value FROM schema_meta WHERE key = ?',
      args: [probeKey],
    });
    const remoteValue = result?.rows?.[0]?.value;
    if (remoteValue !== probeValue) return false;

    await client.execute({ sql: 'DELETE FROM schema_meta WHERE key = ?', args: [probeKey] });
    await syncDb(client);
    return true;
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    console.warn(\`[brain-db] sync verification failed: \${message}\`);
    return false;
  } finally {
    try {
      await remoteClient.execute({ sql: 'DELETE FROM schema_meta WHERE key = ?', args: [probeKey] });
    } catch {
      // best effort cleanup only
    }
    try {
      await remoteClient.close?.();
    } catch {
      // ignore close failures
    }
  }
}
`;

